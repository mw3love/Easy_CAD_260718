import json, os, sys

o = []
def B(i, a, b, c, d, label=None, font=15):
    dd = dict(op="box", x1=a, y1=b, x2=c, y2=d)
    if i: dd["id"] = i
    if label: dd.update(label=label, font=round(font * 1.45))
    o.append(dd)
def T(x, y, t, f=13, k=1.45): o.append(dict(op="text", x=x, y=y, text=t, font=round(f * k)))
def L(pts, head=False, src=None, dst=None):
    dd = dict(op="line", pts=pts, head=head)
    if src: dd["src"] = src
    if dst: dd["dst"] = dst
    o.append(dd)
def P(pts, closed=False): o.append(dict(op="poly", pts=pts, closed=closed))
def C(cx, cy, r, i=None):
    dd = dict(op="circle", cx=cx, cy=cy, r=r)
    if i: dd["id"] = i
    o.append(dd)
def V(x, y, t, f=8):
    """세로 케이블 번호 — 회전이 없으니 글자를 한 줄에 하나씩 세워 쓴다."""
    T(x, y, "\n".join(t), f, 1)

